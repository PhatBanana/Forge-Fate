export const FEATS_BY_ID: Record<string, Feat> = Object.fromEntries(
  FEATS.map((f) => [f.id, f]),
);

/** Apply a feat's 2024 overrides, if it has any and we are in 2024. */
function forRuleset(feat: Feat, ruleset: Ruleset): Feat {
  if (ruleset !== '2024' || !feat.in2024) return feat;
  const { asi, ...rest } = feat.in2024;
  const merged: Feat = { ...feat, ...rest };
  // An explicit null clears the 2014 increase; undefined leaves it alone.
  if (asi === null) delete merged.asi;
  else if (asi) merged.asi = asi;
  return merged;
}

export function featsFor(ruleset: Ruleset): Feat[] {
  return FEATS.filter((f) => (f.rulesets ?? ['2014']).includes(ruleset)).map((f) =>
    forRuleset(f, ruleset),
  );
}

/**
 * Ruleset-aware lookup. `FEATS_BY_ID` returns the base (2014) record, which is
 * wrong anywhere a 2024 character's own numbers are being computed.
 */
export function featById(id: string, ruleset: Ruleset): Feat | undefined {
  const feat = FEATS_BY_ID[id];
  return feat ? forRuleset(feat, ruleset) : undefined;
}
