import type { Ability, ClassId, Condition, ScoreRule } from '../types';

/**
 * Spells, substantially the SRD 5.1 list, plus a few from later books that
 * changed how a class plays - Toll the Dead, Absorb Elements, the Ranger and
 * Paladin smites.
 *
 * Every full caster has something at every spell level they can reach, which is
 * the property the tests pin: the list was once thin above 5th, and a Wizard 15
 * opening the 8th-level tab found nothing there. Half casters correctly stop at
 * 5th, and Paladins and Rangers get no cantrips.
 *
 * Every entry carries the structural facts a sheet needs - level, school, whose
 * list it is on, casting time, range, duration, concentration and ritual - plus
 * written commentary only where there is something to say. A verdict on
 * Fireball is useful; a verdict on Prestidigitation is not, so roughly one in
 * eight entries is deliberately unscored and the UI marks it "unrated" rather
 * than inventing a number.
 *
 * Rules text is summarised, not reproduced. The SRD is CC-BY-4.0 (see README),
 * but a one-line summary is more useful in a builder than a paragraph.
 */

export type School =
  | 'abjuration'
  | 'conjuration'
  | 'divination'
  | 'enchantment'
  | 'evocation'
  | 'illusion'
  | 'necromancy'
  | 'transmutation';

/**
 * How long a spell takes to cast.
 *
 * The first three are the ones the engine reasons about, because they are what
 * compete for your turn. The rest are wall-clock, and they used to collapse
 * into a single `'long'` meaning "an hour or more" - which told a player
 * nothing about whether Find Familiar costs them an hour or Hallow costs them
 * a day. These nine are exactly the distinct times the 319 SRD spells use.
 */
export type CastingTime =
  | 'action'
  | 'bonus'
  | 'reaction'
  | 'minute'
  | '10-minutes'
  | 'hour'
  | '8-hours'
  | '12-hours'
  | '24-hours';

export interface SpellDamage {
  /** At the spell's base level, or a cantrip's level 1 form. */
  dice: string;
  type: string;
  /** Cantrips step at 5/11/17; slot spells add dice per level above base. */
  scaling: 'cantrip' | 'slot' | 'none';
  /** Extra dice per slot level above the spell's own, for 'slot' scaling. */
  perSlot?: string;
  /** A saving throw instead of an attack roll. */
  save?: Ability;
  /** Half damage on a successful save, which most area spells allow. */
  halfOnSave?: boolean;
  /** How many creatures it can realistically catch. 1 for single target. */
  targets?: number;
}

/**
 * What a healing spell restores, mirroring `SpellDamage`.
 *
 * Kept apart from damage rather than folded into it with a negative sign,
 * because the two answer different questions and are never compared: nobody
 * asks whether Cure Wounds out-damages Fire Bolt. The app could rank a
 * Wizard's output and had nothing at all to say to a Cleric until this existed.
 *
 * Mass Heal and Power Word Heal are deliberately absent. "Restore 700 hit
 * points divided as you choose" and "all of them" are not amounts a
 * per-casting average describes, and inventing a number for them would make
 * the healing column lie at exactly the two levels someone would check it.
 */
export interface SpellHealing {
  /** At the spell's own level. Absent for the ones that heal a flat amount. */
  dice?: string;
  /** Extra dice per slot level above the spell's own. */
  perSlot?: string;
  /** Extra flat healing per slot level, which is how Heal scales. */
  perSlotFlat?: number;
  /** Whether your spellcasting modifier is added, which most of them add. */
  addsModifier?: boolean;
  /** A flat amount on top, as Heal and Regenerate have. */
  flat?: number;
  /** How many creatures it can reach. 1 unless it says otherwise. */
  targets?: number;
  /** Cast as a bonus action, which is most of why Healing Word exists. */
  bonusAction?: boolean;
}

/**
 * Verbal, somatic, material - what casting it actually takes.
 *
 * §64. Verified against SRD 5.1, which carries `["V","S","M"]` structurally
 * and the material beside it as prose. That split is the right one and this
 * mirrors it: which of the three a spell needs is a fact with three possible
 * values, and *what* the material is is a sentence only a human reads.
 *
 * `m` present means the spell has a material component, and its value is the
 * SRD's own wording. The two are the same fact upstream - every one of the
 * 319 SRD spells with an M has material text and vice versa, which
 * `srdAudit.test.ts` pins - so one optional field encodes both rather than a
 * boolean and a string that could disagree.
 */
export interface SpellComponents {
  v: boolean;
  s: boolean;
  /** The material, in the SRD's words. Absent means the spell needs none. */
  m?: string;
}

export interface Spell {
  id: string;
  name: string;
  /** 0 for a cantrip. */
  level: number;
  school: School;
  classes: ClassId[];
  castingTime: CastingTime;
  range: string;
  duration: string;
  concentration: boolean;
  ritual: boolean;
  /**
   * What it takes to cast, where the SRD says so.
   *
   * **Absent means unverified, not "no components".** Twenty-five spells the
   * app carries are not in SRD 5.1 - Hex, Toll the Dead, the smites and the
   * rest - and writing their components from the books would be putting an
   * unverifiable claim next to 319 verified ones. `engine/components.ts`
   * therefore leaves the rule unapplied for them rather than applying it in
   * a direction it cannot support, which is the same refusal `canSee` and
   * `attackerSeesTarget` make elsewhere.
   */
  components?: SpellComponents;
  summary: string;
  damage?: SpellDamage;
  healing?: SpellHealing;
  /** Only on spells worth an opinion. */
  note?: string;
  /** Baseline power, 0-10. Absent means the spell is not scored. */
  base?: number;
  rules?: ScoreRule[];
}

