export const SPELLS_BY_ID: Record<string, Spell> = Object.fromEntries(
  SPELLS.map((s) => [s.id, s]),
);

export function spellById(id: string): Spell | undefined {
  return SPELLS_BY_ID[id];
}

/** Every spell on a class's list, at or below a given spell level. */
export function spellsFor(classId: ClassId, maxLevel = 9): Spell[] {
  return SPELLS.filter((s) => s.classes.includes(classId) && s.level <= maxLevel);
}

